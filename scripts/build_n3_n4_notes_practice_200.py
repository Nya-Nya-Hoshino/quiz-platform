def choice(qid, section, difficulty, question, correct, wrong, explanation, typ):
    opts = [correct, *wrong]
    pos = qid % 4
    opts[0], opts[pos] = opts[pos], opts[0]
    return {'id': qid, 'type': typ, 'section': section, 'difficulty': difficulty,
            'score': 2, 'question': question, 'options': opts, 'answer': pos,
            'explanation': explanation}

def alternatives(items, index, field, answer, number=3):
    result=[]
    for item in items[index + 1:] + items[:index]:
        value=item[field]
        if value != answer and value not in result:
            result.append(value)
        if len(result) == number:
            return result
    raise ValueError('not enough distinct distractors')

